    private void btnisesion1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnisesion1ActionPerformed
        // TODO add your handling code here:
           
        
      // Obtener el texto del usuario y de la contraseña de forma segura
    String usuario = txtusuario.getText().trim();
    String contraseña = new String(txtcontraseña.getPassword()).trim();
    
    // 1. Validar si alguno de los campos está vacío
    if (usuario.isEmpty() || contraseña.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, 
            "Debe ingresar el usuario y la contraseña obligatoriamente.", 
            "Campos obligatorios", 
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return; // Detiene la ejecución si hay campos vacíos
    }
    
    // 2. Validar las credenciales (Usuario y Contraseña)
    if (usuario.equals("admin") && contraseña.equals("1234")) {
        javax.swing.JOptionPane.showMessageDialog(this, "Login correcto");
         Formulario frml = new Formulario();
        this.jDesktopPane1.add(frml);
        frml.setVisible(true);
        
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, 
            "Usuario o contraseña incorrectos.", 
            "Error de autenticación", 
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }    
      
    }//GEN-LAST:event_btnisesion1ActionPerformed

