private void configurarTabla() {

    String[] columnas = {
        "ID",
        "Cliente",
        "Fecha de medición",
        "Esfera OD",
        "Esfera OI",
        "Cilindro OD",
        "Cilindro OI",
        "Eje OD",
        "Eje OI",
        "Adición OD",
        "Adición OI",
        "Tipo de medición",
        "Estado"
    };

    DefaultTableModel modeloTabla =
            new DefaultTableModel(null, columnas) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    tablemediciones.setModel(modeloTabla);
    tablemediciones.setRowHeight(25);
    tablemediciones.getTableHeader().setReorderingAllowed(false);
}

private void cargarClientes() {

    jsbCliente.removeAllItems();
    jsbCliente.addItem("Seleccione un cliente");

    ClientesController controlador =
            new ClientesController(new ClientesDAOImpl());

    listaClientes = controlador.listarClientes();

    for (modelo.Clientes cliente : listaClientes) {
        jsbCliente.addItem(
                cliente.getId() + " - " + cliente.getNombre()
        );
    }
}

private void cargarMediciones() {

    DefaultTableModel modeloTabla =
            (DefaultTableModel) tablemediciones.getModel();

    modeloTabla.setRowCount(0);

    MedicionDAOImpl dao = new MedicionDAOImpl();

    List<Medicion> lista = dao.listar();

    for (Medicion m : lista) {

        String nombreCliente = "Desconocido";

        for (modelo.Clientes cliente : listaClientes) {
            if (cliente.getId() == m.getIdCliente()) {
                nombreCliente = cliente.getNombre();
                break;
            }
        }

        Object[] fila = {
            m.getId(),
            nombreCliente,
            m.getFechaMedicion(),
            m.getEsferaOD(),
            m.getEsferaOI(),
            m.getCilindroOD(),
            m.getCilindroOI(),
            m.getEjeOD(),
            m.getEjeOI(),
            m.getAdicionOD(),
            m.getAdicionOI(),
            m.getTipoMedicion(),
            m.getEstado()
        };

        modeloTabla.addRow(fila);
    }
}


